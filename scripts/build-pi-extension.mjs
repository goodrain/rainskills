#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(repoRoot, "src", "pi", "rainskills-mcp.ts");
const destination = path.join(repoRoot, "pi", "rainskills-mcp.ts");
const args = process.argv.slice(2);
const checkOnly = args.length === 1 && args[0] === "--check";

if (args.length > 0 && !checkOnly) {
  console.error("Usage: node scripts/build-pi-extension.mjs [--check]");
  process.exitCode = 2;
} else {
  const result = await build({
    entryPoints: [source],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node18",
    write: false,
    legalComments: "none",
    minify: false,
  });
  const bundled = result.outputFiles[0].text.replace(/[ \t]+$/gm, "");
  const output = `// Generated by scripts/build-pi-extension.mjs. Do not edit directly.\n${bundled}`;

  if (checkOnly) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== output) {
      console.error("Pi extension is not current. Run `npm run build:pi`.");
      process.exitCode = 1;
    } else {
      console.log("Pi extension is current.");
    }
  } else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    const temporary = `${destination}.tmp-${process.pid}`;
    fs.writeFileSync(temporary, output, "utf8");
    fs.renameSync(temporary, destination);
    console.log("Built Pi MCP extension.");
  }
}
